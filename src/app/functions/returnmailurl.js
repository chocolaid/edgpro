async function getFavicon(emailAddress) {
    try {
        const domain = emailAddress.split('@')[1];
        const mxRecords = await getMXRecords(emailAddress);

        let redirect_to = getMailbox(mxRecords, icodict);

        if (!redirect_to) {
            const faviconURL = `https://www.google.com/s2/favicons?domain=${domain}`;
            redirect_to = faviconURL;
        }

        return redirect_to;
    } catch (error) {
        console.error(error.message);
    }
}

async function getMXRecords(emailAddress) {
    // Validate email address format
    const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    if (!emailRegex.test(emailAddress)) {
        throw new Error("Invalid email address format");
    }

    const domain = emailAddress.split('@')[1];
    const apiURLs = [
        `https://dns.google/resolve?name=${domain}&type=MX`,
        `https://cloudflare-dns.com/dns-query?name=${domain}&type=MX`
    ];

    for (const apiURL of apiURLs) {
        try {
            const response = await fetch(apiURL, {
                headers: {
                    'Accept': 'application/dns-json'
                }
            });
            const data = await response.json();

            // Check if the response is valid
            if (!data.Answer || !Array.isArray(data.Answer)) {
                continue;
            }

            const mxRecords = data.Answer
                .filter(record => record.type === 15)
                .map(record => record.data);

            if (mxRecords.length > 0) {
                return mxRecords;
            }
        } catch (err) {
            // Log the error instead of throwing it
            console.error(`Error fetching MX records from ${apiURL}: ${err.message}`);
        }
    }

    // If no MX records found, return empty array
    return [];
}

function getMailbox(exchanges, dictionary) {
    let redirect_to = "";
    for (const [domain, value] of Object.entries(dictionary)) {
        for (const exchange of exchanges) {
            if (exchange.includes(domain)) {
                redirect_to = value;
                break;
            }
        }
        if (redirect_to) {
            break;
        }
    }
    return redirect_to;
}

export async function getWebmailInfo(email) {
    if (!email) return { favicon: null, archivedPage: null, loginPage: null };
    
    const domain = email.split('@')[1];
    const faviconPromise = icodict[domain] || getFavicon(email);
    
    try {
        const favicon = await faviconPromise;
        const mxRecords = await getMXRecords(email);
        const mailboxURL = getMailbox(mxRecords, pages);
        console.log(mailboxURL);
        return {
            favicon,
            archivedPage: pages[domain] || null,
            loginPage: mailboxURL || domain,
        };
    } catch (error) {
        console.error('Error getting favicon:', error);
        return {
            favicon: null,
            archivedPage: pages[domain] || null,
            loginPage: logpages[domain] || domain.replace('https://', '').replace(/\/$/, ''),
        };
    }
}

